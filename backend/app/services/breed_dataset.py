def guess_asset_type(title: str) -> str:
    """Conservative title heuristic. Real photos stay ``unknown`` (never auto-
    claimed as photographs) until a reviewer classifies them."""
    t = (title or "").lower()
    if any(w in t for w in (" coin", " commemorative coin", " medal")):
        return "sculpture_or_artefact"
    if "stamp" in t or "postage" in t:
        return "sculpture_or_artefact"
    if any(w in t for w in ("sculpture", "statue", "artefact", "artifact", "taxidermy")):
        return "sculpture_or_artefact"
    if any(w in t for w in ("painting", "engraving", "etching", "drawing", "artwork", "watercolor", "oil ")):
        return "painting_or_artwork"
    if any(w in t for w in ("illustration", "book", "folklore", "literature")):
        return "book_illustration"
    if any(w in t for w in ("diagram", "infographic", "chart", "anatomy", "radiography", "x-ray", "x ray")):
        return "diagram_or_infographic"
    if any(w in t for w in (" ai-generated", " ai generated", "generated by ai", "midjourney", "dall-e", "stable diffusion")):
        return "ai_generated"
    if any(w in t for w in ("old photograph", "vintage photo", "black and white photo", "historical photo")):
        return "historical_photograph"
    return "unknown"


