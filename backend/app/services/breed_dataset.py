# --- retrieval relevance -----------------------------------------------------
# Commons full-text search is only a fallback for thin categories, and it
# matches any file whose *text* mentions the words. "Manx cats" therefore
# returns Isle of Man TT motorcycles ("2019 Senior Manx Grand Prix") and
# "Siamese cats" returns book plates, swans and unrelated portraits. A search
# hit must name the breed in the file title; a direct category member is a
# trustworthy hint on its own but still drops known non-cat subjects.
BREED_TITLE_TOKENS: Dict[str, Tuple[str, ...]] = {
    "manx": ("manx",),
    "siamese": ("siamese",),
    "norwegian-forest-cat": ("norwegian forest", "skogkatt"),
    "tonkinese": ("tonkinese",),
    "siberian": ("siberian",),
}
IRRELEVANT_TITLE_PATTERN = re.compile(
    r"\b(?:"
    r"grand prix|motorbike|motor cycle|motorcycle|motorsport|norton|suzuki|"
    r"yamaha|honda|kawasaki|ducati|triumph|racing|racer|race|rally|"
    r"steam packet|ferry|steamship|ship|yacht|hovercraft|railway|locomotive|"
    r"tram|bus|aircraft|aeroplane|airplane|"
    r"football|rugby|cricket|cyclist|bicycle|athlete|marathon|stadium|"
    r"gravestone|headstone|memorial|war memorial"
    r")s?\b", re.I)
# Breeds that are routinely mis-filed under a target breed (Cymric is the
# long-haired Manx variant but a distinct CFA breed; bobtails are not Manx).
FOREIGN_BREED_TOKENS = (
    "cymric", "owyhee bob", "mountain bob", "pixie-bob", "japanese bobtail",
    "american bobtail", "karelian bobtail", "kurilian bobtail",
)

# --- colour gate -------------------------------------------------------------
# Users cannot judge a breed from a monochrome scan: coat colour is a primary
# Siamese/Manx cue. White-balancing first removes a global sepia/cyan cast, so
# a toned historical scan collapses to grey while a real colour photo keeps a
# broad hue spread. Thresholds were calibrated on the pilot + round-2 batches
# (see Documentation/Breed-Dataset-Collection.md).
HUE_BINS = 36
COLOUR_SAMPLE = 160
MONOCHROME_MAX_COLOUR_FRACTION = 0.02   # hard floor: essentially grey
TONED_MAX_COLOUR_FRACTION = 0.06        # sepia/duotone: tint mostly cancels
TONED_MAX_HUE_ENTROPY = 2.2
TONED_MIN_DOMINANT_SHARE = 0.45

MIN_WIDTH = 400
MIN_HEIGHT = 400
ALLOWED_MIMES = {"image/jpeg", "image/png"}
# Licence allow-list: public domain, CC0, CC BY, CC BY-SA (any version).
# Everything else (NC, ND, missing author, unknown) is rejected.
_REJECT = re.compile(r"\b(NC|ND|no deriv|no-deriv|non-?commercial)\b", re.I)
_ALLOW = re.compile(
    r"(public domain|CC0|CC BY(-SA)?\s+\d\.\d|CC BY-SA|CC BY\s*(\d|$)|"
    r"Attribution|no restrictions|CC [A-Z-]+\s*\d\.\d)", re.I)
HTML_TAG = re.compile(r"<[^>]+>")


def clean(value: Optional[str]) -> str:
    if not value:
        return ""
    return html.unescape(HTML_TAG.sub("", value)).strip()


def license_decision(author: str, license_name: str) -> tuple[bool, str]:
    """Return (accepted, reason). Missing attribution/licence always rejects."""
    if not author or not license_name:
        return False, "missing_attribution"
    if _REJECT.search(license_name):
        return False, "nc_nd_or_unknown_restriction"
    if "CC BY" not in license_name.upper() and "CC0" not in license_name.upper() \
            and "PUBLIC DOMAIN" not in license_name.upper() and "ATTRIBUTION" not in license_name.upper() \
            and "NO RESTRICTIONS" not in license_name.upper():
        return False, "unrecognised_license"
    if _ALLOW.search(license_name) is None:
        return False, "unrecognised_license"
    return True, "accepted"


def sha256_bytes(data: bytes) -> str:
    return hashlib.sha256(data).hexdigest()


def dhash64(image: Image.Image, hash_size: int = 8) -> int:
    """64-bit difference hash (perceptual near-duplicate detection)."""
    g = image.convert("L").resize((hash_size + 1, hash_size), Image.Resampling.BILINEAR)
    px = g.tobytes()
    bits = 0
    for r in range(hash_size):
        for c in range(hash_size):
            bits = (bits << 1) | (1 if px[r * (hash_size + 1) + c] > px[r * (hash_size + 1) + c + 1] else 0)
    return bits


def hamming(a: int, b: int) -> int:
    return bin(a ^ b).count("1")


def is_near_duplicate(ph: int, seen: Iterable[int], threshold: int = 5) -> bool:
    return any(hamming(ph, s) <= threshold for s in seen)


def breed_title_tokens(breed_id: str, category: str = "") -> Tuple[str, ...]:
    """Title tokens that identify the target breed (breed map, else category)."""
    tokens = BREED_TITLE_TOKENS.get(breed_id or "")
    if tokens:
        return tokens
    base = re.sub(r"\s*\(cat\)\s*$", "", category or "", flags=re.I)
    base = re.sub(r"\s+cats?$", "", base, flags=re.I).strip().lower()
    return (base,) if base else ()


def title_mentions_breed(title: str, breed_id: str, category: str = "") -> bool:
    """Whole-word/phrase match so "Manxman" (a ship) is not a Manx cat."""
    lowered = (title or "").lower()
    return any(re.search(rf"\b{re.escape(tok)}\b", lowered)
               for tok in breed_title_tokens(breed_id, category))


def title_is_irrelevant(title: str) -> bool:
    """Titles about vehicles, races, sports or memorials are never a cat photo."""
    return bool(IRRELEVANT_TITLE_PATTERN.search(title or ""))


def title_has_foreign_breed(title: str, breed_id: str, category: str = "") -> bool:
    """True when the title names a different breed and not the target."""
    lowered = (title or "").lower()
    if any(tok in lowered for tok in breed_title_tokens(breed_id, category)):
        return False
    return any(tok in lowered for tok in FOREIGN_BREED_TOKENS)


def colour_profile(image: Image.Image) -> Dict[str, Any]:
    """White-balanced colour statistics used by the collection colour gate.

    ``colour_fraction`` is the share of pixels that stay chromatic after a
    grey-world white balance (a sepia scan loses its tint and drops to ~0).
    ``hue_entropy``/``dominant_share`` describe how much of that colour is one
    narrow band (duotone) versus a real, varied colour photo.
    """
    im = image.convert("RGB")
    im.thumbnail((COLOUR_SAMPLE, COLOUR_SAMPLE))
    raw = im.tobytes()
    pixels = [(raw[i], raw[i + 1], raw[i + 2]) for i in range(0, len(raw), 3)]
    total = len(pixels) or 1
    means = [max(1.0, sum(p[i] for p in pixels) / total) for i in range(3)]
    target = sum(means) / 3.0
    scale = [target / m for m in means]
    bins = [0] * HUE_BINS
    coloured = 0
    for r, g, b in pixels:
        r = min(255, r * scale[0])
        g = min(255, g * scale[1])
        b = min(255, b * scale[2])
        mx, mn = max(r, g, b), min(r, g, b)
        if mx - mn >= 20 and mx >= 45:
            hue, _, _ = colorsys.rgb_to_hsv(r / 255.0, g / 255.0, b / 255.0)
            bins[int(hue * HUE_BINS) % HUE_BINS] += 1
            coloured += 1
    fraction = coloured / total
    if coloured:
        probs = [c / coloured for c in bins if c]
        entropy = -sum(p * math.log2(p) for p in probs)
        dominant = max(bins) / coloured
        used = sum(1 for c in bins if c / coloured >= 0.01)
    else:
        entropy, dominant, used = 0.0, 0.0, 0
    return {"colour_fraction": round(fraction, 4),
            "hue_entropy": round(entropy, 3),
            "dominant_share": round(dominant, 3),
            "hue_bins": used}


def monochrome_reason(profile: Dict[str, Any]) -> Optional[str]:
    """``greyscale`` / ``toned_monochrome`` when a photo carries no usable colour."""
    fraction = float(profile.get("colour_fraction") or 0.0)
    if fraction < MONOCHROME_MAX_COLOUR_FRACTION:
        return "greyscale"
    if (fraction < TONED_MAX_COLOUR_FRACTION
            and float(profile.get("hue_entropy") or 0.0) < TONED_MAX_HUE_ENTROPY
            and float(profile.get("dominant_share") or 0.0) >= TONED_MIN_DOMINANT_SHARE):
        return "toned_monochrome"
    return None


def validate_image_bytes(data: bytes) -> tuple[Image.Image, int, int, str]:
    """Decode check; returns (image, width, height, format). Raises ValueError."""
    import io
    try:
        with Image.open(io.BytesIO(data)) as im:
            im.verify()
        with Image.open(io.BytesIO(data)) as im:
            im.load()
            w, h = im.size
            fmt = (im.format or "").lower()
            if fmt not in ("jpeg", "png"):
                raise ValueError(f"unsupported_format:{fmt}")
            if w < MIN_WIDTH or h < MIN_HEIGHT:
                raise ValueError(f"below_min_resolution:{w}x{h}")
            return im.copy(), w, h, fmt
    except (Image.UnidentifiedImageError, EOFError, OSError, ValueError) as exc:
        if isinstance(exc, ValueError) and str(exc).startswith(("below_min", "unsupported")):
            raise
        raise ValueError(f"integrity_failure:{exc}") from exc


class CommonsClient:
    """Throttled Commons client with retry/backoff (mirrors validation sampler)."""

    def __init__(self, min_interval: float = 2.0, image_interval: float = 0.6, retries: int = 4):
        self.min_interval = min_interval
        self.image_interval = image_interval
        self.retries = retries
        self._last_call = 0.0
        self._last_download = 0.0
        self.requests = 0
        self.downloads = 0

    def _throttle(self):
        elapsed = time.monotonic() - self._last_call
        if elapsed < self.min_interval:
            time.sleep(self.min_interval - elapsed)
        self._last_call = time.monotonic()

    def _throttle_download(self):
        elapsed = time.monotonic() - self._last_download
        if elapsed < self.image_interval:
            time.sleep(self.image_interval - elapsed)
        self._last_download = time.monotonic()

    def _open(self, url: str, *, timeout: int = 60) -> bytes:
        req = urllib.request.Request(url, headers={"User-Agent": USER_AGENT})
        last: Optional[Exception] = None
        for attempt in range(self.retries):
            try:
                with urllib.request.urlopen(req, timeout=timeout) as resp:  # noqa: S310
                    return resp.read()
            except urllib.error.HTTPError as exc:
                last = exc
                if exc.code not in (429, 500, 502, 503, 504):
                    raise
                time.sleep(int(exc.headers.get("Retry-After", 10)) + 2 * (attempt + 1))
            except urllib.error.URLError as exc:
                last = exc
                time.sleep(3 * (attempt + 1))
        raise RuntimeError(f"request failed after {self.retries} attempts: {last}")

    def api(self, params: Dict[str, Any]) -> Dict[str, Any]:
        self._throttle()
        self.requests += 1
        return json.loads(self._open(COMMONS_API + "?" + urllib.parse.urlencode(params)).decode("utf-8"))

    def download(self, url: str, destination: Path) -> None:
        self._throttle_download()
        self.downloads += 1
        destination.parent.mkdir(parents=True, exist_ok=True)
        destination.write_bytes(self._open(url))


def _category_pages(client: CommonsClient, category: str, limit: int, gcmtype: str = "file",
                    cont: str | None = None) -> dict:
    params: Dict[str, Any] = {
        "action": "query", "generator": "categorymembers", "gcmtitle": f"Category:{category}",
        "gcmtype": gcmtype, "gcmlimit": min(500, max(limit, 50)), "prop": "imageinfo",
        "iiprop": "url|mime|size|extmetadata", "iiurlwidth": 960, "format": "json"}
    if cont:
        params["gcmcontinue"] = cont
    return client.api(params)


def list_category_files(client: CommonsClient, category: str, limit: int,
                        breed_id: str = "") -> List[Dict[str, Any]]:
    """Return imageinfo rows for a Commons category (jpeg/png, min size, no junk titles).

    Recurses one level into subcategories (e.g. Norwegian Forest cats has only
    subcats), then falls back to Commons full-text search so filing quirks in a
    few thin categories don't starve the run. Pages are deduped by title.

    Every row records where it came from (``retrieval``): ``search`` rows must
    name the target breed in the file title, while category/subcategory rows are
    trusted as a retrieval hint. Titles naming vehicles, races or another breed
    are dropped either way.
    """
    rows: List[Dict[str, Any]] = []
    seen: set[str] = set()

    def add_pages(data: Dict[str, Any], retrieval: str) -> None:
        for page in (data.get("query", {}).get("pages", {}) or {}).values():
            title = page.get("title", "")
            infos = page.get("imageinfo") or []
            if not infos or title in seen:
                continue
            seen.add(title)
            info = infos[0]
            if info.get("mime") not in ALLOWED_MIMES:
                continue
            if int(info.get("width") or 0) < MIN_WIDTH or int(info.get("height") or 0) < MIN_HEIGHT:
                continue
            if any(tok in title.lower() for tok in SKIP_TITLE_TOKENS):
                continue
            if title_is_irrelevant(title) or title_has_foreign_breed(title, breed_id, category):
                continue
            if retrieval == "search" and not title_mentions_breed(title, breed_id, category):
                continue
            meta = info.get("extmetadata", {})
            rows.append({"title": title, "url": info.get("thumburl") or info.get("url"),
                         "description_url": info.get("descriptionurl", ""),
                         "author": clean(meta.get("Artist", {}).get("value")),
                         "license": clean(meta.get("LicenseShortName", {}).get("value")),
                         "license_url": clean(meta.get("LicenseURL", {}).get("value")),
                         "width": int(info.get("width") or 0), "height": int(info.get("height") or 0),
                         "mime": info.get("mime"), "retrieval": retrieval})

    add_pages(_category_pages(client, category, limit), "category")
    # One level of subcategories.
    if len(rows) < limit:
        subs = _category_pages(client, category, limit, gcmtype="subcat")
        for page in (subs.get("query", {}).get("pages", {}) or {}).values():
            sub = page.get("title", "").removeprefix("Category:")
            if sub and not title_is_irrelevant(sub) and not title_has_foreign_breed(sub, breed_id, category):
                add_pages(_category_pages(client, sub, limit), "subcategory")
            if len(rows) >= limit:
                break
    # Search fallback (filetype bitmap + breed phrase, namespace File only).
    if len(rows) < limit:
        data = client.api({
            "action": "query", "generator": "search", "gsrsearch": f"{category} filetype:bitmap",
            "gsrnamespace": 6, "gsrlimit": min(500, max(limit * 3, 50)), "prop": "imageinfo",
            "iiprop": "url|mime|size|extmetadata", "iiurlwidth": 960, "format": "json"})
        add_pages(data, "search")
    return rows[:limit]


def legacy_test_hashes(repo_root: Path) -> Set[str]:
    """SHA-256 set of the frozen 86-image historical test set (never touch)."""
    val_dir = repo_root / "backend/tests/fixtures/breed-validation/images"
    hashes: Set[str] = set()
    if val_dir.exists():
        for f in val_dir.rglob("*"):
            if f.is_file():
                hashes.add(sha256_bytes(f.read_bytes()))
    return hashes


def load_manifest(path: Path) -> List[Dict[str, Any]]:
    if not path.exists():
        return []
    return [json.loads(line) for line in path.read_text(encoding="utf-8").splitlines() if line.strip()]


def append_manifest(path: Path, row: Dict[str, Any]) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    with path.open("a", encoding="utf-8") as fh:
        fh.write(json.dumps(row, ensure_ascii=True) + "\n")


QUALITY_FLAG_IRRELEVANT = "irrelevant_subject"
QUALITY_FLAG_FOREIGN = "foreign_breed"
QUALITY_FLAG_UNREADABLE = "unreadable"


def quality_flags_for_row(row: Dict[str, Any], dataset_root: Path) -> List[str]:
    """Derived quality flags for an already-collected row.

    Read-only: it inspects the stored file and title, and never changes a
    review decision, split or label. Used to surface the pre-gate round-2 batch
    for manual rejection instead of deleting it.
    """
    flags: List[str] = []
    title = row.get("title", "")
    breed_id = row.get("breed_id", "")
    category = row.get("category_hint", "")
    if title_is_irrelevant(title):
        flags.append(QUALITY_FLAG_IRRELEVANT)
    elif title_has_foreign_breed(title, breed_id, category):
        flags.append(QUALITY_FLAG_FOREIGN)
    path = dataset_root / row["file"] if row.get("file") else None
    reason = None
    if path is not None and path.exists():
        try:
            with Image.open(path) as im:
                reason = monochrome_reason(colour_profile(im))
        except (OSError, ValueError):
            flags.append(QUALITY_FLAG_UNREADABLE)
    if reason:
        flags.append(reason)
    return flags


def flag_manifest_quality(dataset_root: Path, apply: bool = True) -> Dict[str, Any]:
    """Recompute ``quality_flags`` for every manifest row (append-safe rewrite).

    Nothing is deleted and no review decision is invented: flagged rows stay
    ``pending`` so a reviewer decides them. ``apply=False`` is a dry run.
    """
    manifest_path = dataset_root / "manifest.jsonl"
    rows = load_manifest(manifest_path)
    flagged: List[Dict[str, Any]] = []
    by_flag: Dict[str, int] = {}
    by_breed: Dict[str, int] = {}
    for r in rows:
        flags = quality_flags_for_row(r, dataset_root)
        r["quality_flags"] = flags
        if not flags:
            continue
        flagged.append({"id": r["id"], "breed_id": r["breed_id"],
                        "title": r.get("title"), "flags": flags})
        by_breed[r["breed_id"]] = by_breed.get(r["breed_id"], 0) + 1
        for flag in flags:
            by_flag[flag] = by_flag.get(flag, 0) + 1
    if apply and rows:
        tmp = dataset_root / "manifest.jsonl.tmp"
        tmp.write_text("".join(json.dumps(r, ensure_ascii=True) + "\n" for r in rows),
                       encoding="utf-8")
        tmp.replace(manifest_path)
    return {"generated": time.strftime("%Y-%m-%d"), "scanned": len(rows),
            "flagged": len(flagged), "by_flag": by_flag, "by_breed": by_breed,
            "applied": bool(apply and rows), "items": flagged}


def collect_breed(
    breed_id: str, category: str, per_breed: int, client: CommonsClient,
    dataset_root: Path, legacy_hashes: Set[str], known_sha: Set[str],
    known_ph: List[int],
) -> Dict[str, int]:
    """Download up to ``per_breed`` *new* candidates for one breed.

    ``per_breed`` is the number of new rows this run, not the breed total: the
    second collection round tops up thin breeds and must not be blocked just
    because the breed already has rows (rejected ones included). Every file is
    checked against the exact SHA-256, the frozen legacy test set, the existing
    Commons titles and the perceptual (dhash) near-duplicate set, so already
    collected images and their re-encodes cannot be collected again.
    """
    manifest = dataset_root / "manifest.jsonl"
    counts = {"listed": 0, "downloaded": 0, "written": 0, "rejected_license": 0,
              "rejected_title": 0, "rejected_resolution": 0, "exact_dupe": 0,
              "near_dupe": 0, "legacy_overlap": 0, "already_collected": 0,
              "integrity_fail": 0, "rejected_irrelevant": 0,
              "rejected_monochrome": 0}
    if per_breed <= 0:
        return counts
    # Snapshot once instead of re-reading the manifest inside the loop; titles
    # guard against the same Commons file being re-downloaded at a new thumb size.
    existing = load_manifest(manifest)
    known_titles = {r["title"] for r in existing if r.get("title")}
    files = list_category_files(client, category, max(per_breed * 10, 100), breed_id)
    counts["listed"] = len(files)
    for f in files:
        if counts["written"] >= per_breed:
            break
        if f["title"] in known_titles:
            counts["already_collected"] += 1
            continue
        # Defence in depth: a caller may pass unfiltered listings (or an older
        # search response), so the relevance rules run again here.
        if title_is_irrelevant(f["title"]) or title_has_foreign_breed(f["title"], breed_id, category):
            counts["rejected_irrelevant"] += 1
            continue
        if f.get("retrieval") == "search" and not title_mentions_breed(f["title"], breed_id, category):
            counts["rejected_irrelevant"] += 1
            continue
        ok, reason = license_decision(f["author"], f["license"])
        if not ok:
            counts["rejected_license"] += 1
            continue
        tmp = dataset_root / "images/candidates" / breed_id / "_tmp.jpg"
        try:
            client.download(f["url"], tmp)
            data = tmp.read_bytes()
        except Exception:
            counts["integrity_fail"] += 1
            continue
        digest = sha256_bytes(data)
        if digest in known_sha:
            counts["exact_dupe"] += 1
            tmp.unlink(missing_ok=True)
            continue
        if digest in legacy_hashes:
            counts["legacy_overlap"] += 1
            tmp.unlink(missing_ok=True)
            continue
        try:
            image, w, h, fmt = validate_image_bytes(data)
        except ValueError as exc:
            if "below_min_resolution" in str(exc):
                counts["rejected_resolution"] += 1
            else:
                counts["integrity_fail"] += 1
            tmp.unlink(missing_ok=True)
            continue
        # Coat colour is a primary breed cue, so a monochrome or toned scan is
        # not reviewable material — reject before it reaches the manifest.
        profile = colour_profile(image)
        if monochrome_reason(profile):
            counts["rejected_monochrome"] += 1
            tmp.unlink(missing_ok=True)
            continue
        ph = dhash64(image)
        if is_near_duplicate(ph, known_ph):
            counts["near_dupe"] += 1
            tmp.unlink(missing_ok=True)
            continue
        dest = dataset_root / "images/candidates" / breed_id / f"{digest}.jpg"
        dest.parent.mkdir(parents=True, exist_ok=True)
        dest.write_bytes(data)
        tmp.unlink(missing_ok=True)
        known_sha.add(digest)
        known_ph.append(ph)
        known_titles.add(f["title"])
        counts["downloaded"] += 1
        counts["written"] += 1
        append_manifest(manifest, {
            "id": digest, "breed_id": breed_id, "split": "candidates",
            "file": f"images/candidates/{breed_id}/{digest}.jpg", "sha256": digest,
            "phash": format(ph, "016x"), "source": "wikimedia-commons",
            "title": f["title"], "description_url": f["description_url"],
            "author": f["author"], "license": f["license"],
            "license_url": f["license_url"],
            "attribution_required": True, "width": f["width"], "height": f["height"],
            "bytes": len(data), "label_confidence": "unverified", "reviewers": [],
            "review_status": "pending",
            "audit_reason": None, "collected_at": time.strftime("%Y-%m-%d"),
            "category_hint": category,
            "retrieval": f.get("retrieval", "category"),
            "quality": profile, "quality_flags": [],
            "asset_type": guess_asset_type(f["title"]),
            "training_eligible": False,
            "exclusion_reason": None,
        })
    return counts


def progress_report(dataset_root: Path, target: int = 230) -> Dict[str, Any]:
    rows = load_manifest(dataset_root / "manifest.jsonl")
    by: Dict[str, int] = {}
    for r in rows:
        if r.get("split") == "candidates":
            by[r["breed_id"]] = by.get(r["breed_id"], 0) + 1
    per = {b: {"candidates": by.get(b, 0), "target": target,
               "shortage": max(0, target - by.get(b, 0))} for b in CATEGORY_BY_BREED}
    return {"generated": time.strftime("%Y-%m-%d"), "target_per_breed": target,
            "total_candidates": sum(by.values()), "per_breed": per}
